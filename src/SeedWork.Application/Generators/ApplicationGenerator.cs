using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace SeedWork.Application.Generators;

[Generator]
public sealed class ApplicationGenerator : ISourceGenerator
{
    private static readonly SymbolDisplayFormat Format = SymbolDisplayFormat.FullyQualifiedFormat;
    private static readonly DiagnosticDescriptor Duplicate = new("SWA001", "Duplicate use case", "More than one implementation of '{0}' was found", "SeedWork.Application", DiagnosticSeverity.Error, true);
    private static readonly DiagnosticDescriptor Invalid = new("SWA002", "Invalid application type", "Type '{0}' cannot be generated: {1}", "SeedWork.Application", DiagnosticSeverity.Error, true);

    public void Initialize(GeneratorInitializationContext context) { }

    public void Execute(GeneratorExecutionContext context)
    {
        var compilation = context.Compilation;
        var resultContract = compilation.GetTypeByMetadataName("SeedWork.Application.IUseCase`2");
        var resultStep = compilation.GetTypeByMetadataName("SeedWork.Application.IUseCaseStep`2");
        if (resultContract is null || resultStep is null) return;
        if (!AllTypes(compilation.Assembly.GlobalNamespace).Any(t => t.AllInterfaces.Any(i => Same(i.OriginalDefinition, resultContract)))) return;

        var handlers = new List<(INamedTypeSymbol Type, INamedTypeSymbol Contract)>();
        var steps = new List<INamedTypeSymbol>();
        foreach (var type in AllTypes(compilation.Assembly.GlobalNamespace))
        {
            var useCases = type.AllInterfaces.Where(i => Same(i.OriginalDefinition, resultContract)).ToArray();
            var stepContracts = type.AllInterfaces.Where(i => Same(i.OriginalDefinition, resultStep)).ToArray();
            if (useCases.Length == 0 && stepContracts.Length == 0) continue;
            var valid = type.TypeKind == TypeKind.Class && !type.IsAbstract && type.ContainingType is null &&
                        (type.DeclaredAccessibility == Accessibility.Public || type.DeclaredAccessibility == Accessibility.Internal);
            if (!valid)
            {
                Report(context, Invalid, type, type.Name, "it must be a top-level, concrete, accessible class");
                continue;
            }
            if (useCases.Length > 0)
            {
                if (type.Arity != 0) Report(context, Invalid, type, type.Name, "use cases cannot be generic");
                else foreach (var contract in useCases) handlers.Add((type, contract));
            }
            if (stepContracts.Length > 0)
            {
                if (type.Arity > 2 || type.TypeParameters.Any(p => p.HasConstructorConstraint || p.HasReferenceTypeConstraint || p.HasValueTypeConstraint || p.HasUnmanagedTypeConstraint || p.HasNotNullConstraint || p.ConstraintTypes.Any(c => c.TypeKind != TypeKind.Interface)))
                    Report(context, Invalid, type, type.Name, "generic steps support only interface constraints");
                else if (type.Arity > 0 && !stepContracts.Any(i => GenericStepShape(type, i, resultStep)))
                    Report(context, Invalid, type, type.Name, "generic step parameters must match the step contract in order");
                else steps.Add(type);
            }
        }
        if (handlers.Count == 0) return;
        foreach (var group in handlers.GroupBy(h => h.Contract, SymbolEqualityComparer.Default))
            if (group.Count() > 1)
                context.ReportDiagnostic(Diagnostic.Create(Duplicate, group.First().Type.Locations.FirstOrDefault(), group.Key?.ToDisplayString() ?? "unknown"));
        if (handlers.GroupBy(h => h.Contract, SymbolEqualityComparer.Default).Any(g => g.Count() > 1)) return;

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine("namespace SeedWork.Application;");
        source.AppendLine("public static class GeneratedApplicationRegistration");
        source.AppendLine("{");
        source.AppendLine("    public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddSeedWorkApplication(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services, params global::SeedWork.Application.IApplicationPipelineConfiguration[] configurations)");
        source.AppendLine("    {");
        source.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(services);");
        source.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(configurations);");
        source.AppendLine("        for (var i = 0; i < configurations.Length; i++)");
        source.AppendLine("            if (configurations[i] is null) throw new global::System.ArgumentException($\"Configuration at index {i} is null.\", nameof(configurations));");
        source.AppendLine("        var registry = new global::SeedWork.Application.PipelineRegistry(new global::SeedWork.Application.PipelineDescriptor[]");
        source.AppendLine("        {");
        var applicable = handlers.Select(h => steps.Where(s => Compatible(s, h.Contract, resultStep)).ToArray()).ToArray();
        for (var i = 0; i < handlers.Count; i++)
        {
            var c = handlers[i].Contract;
            var response = "typeof(" + Name(c.TypeArguments[1]) + ")";
            source.Append("            new(typeof(").Append(Name(c.TypeArguments[0])).Append("), ").Append(response).Append(", new global::System.Type[] { ");
            source.Append(string.Join(", ", applicable[i].Select(s => "typeof(" + OpenName(s) + ")")));
            source.AppendLine(" }),");
        }
        source.AppendLine("        }, configurations);");
        source.AppendLine("        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddSingleton(services, registry);");
        foreach (var step in steps.GroupBy(Name).Select(g => g.First()).OrderBy(Name))
            source.Append("        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped(services, typeof(").Append(OpenName(step)).AppendLine("));");
        foreach (var handler in handlers.Select(h => h.Type).GroupBy(Name).Select(g => g.First()).OrderBy(Name))
            source.Append("        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped(services, typeof(").Append(Name(handler)).AppendLine("));");
        for (var i = 0; i < handlers.Count; i++)
        {
            source.Append("        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddScoped<").Append(Name(handlers[i].Contract)).Append(">(services, sp => new Wrapper").Append(i).Append("((").Append(Name(handlers[i].Type)).Append(")global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService(sp, typeof(").Append(Name(handlers[i].Type)).Append(")), registry, sp));").AppendLine();
        }
        source.AppendLine("        return services;");
        source.AppendLine("    }");
        for (var i = 0; i < handlers.Count; i++) EmitWrapper(source, handlers[i], applicable[i], i);
        source.AppendLine("}");
        context.AddSource("SeedWorkApplication.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static void EmitWrapper(StringBuilder source, (INamedTypeSymbol Type, INamedTypeSymbol Contract) handler, INamedTypeSymbol[] steps, int index)
    {
        var c = handler.Contract;
        var req = Name(c.TypeArguments[0]);
        var response = Name(c.TypeArguments[1]);
        var stepContract = $"global::SeedWork.Application.IUseCaseStep<{req}, {response}>";
        source.Append("    private sealed class Wrapper").Append(index).Append(" : ").Append(Name(c)).AppendLine();
        source.AppendLine("    {");
        source.Append("        private readonly ").Append(Name(handler.Type)).AppendLine(" _handler;");
        source.AppendLine("        private readonly global::SeedWork.Application.PipelineRegistry _registry;");
        source.AppendLine("        private readonly global::System.IServiceProvider _services;");
        source.Append("        public Wrapper").Append(index).Append("(").Append(Name(handler.Type)).Append(" handler, global::SeedWork.Application.PipelineRegistry registry, global::System.IServiceProvider services)").AppendLine();
        source.AppendLine("        { _handler = handler; _registry = registry; _services = services; }");
        source.Append("        public global::System.Threading.Tasks.Task<").Append(response).Append("> ExecuteAsync(").Append(req).Append(" request, global::System.Threading.CancellationToken cancellationToken = default)").AppendLine();
        source.Append("            => global::SeedWork.Application.PipelineInvoker.InvokeAsync<").Append(req).Append(", ").Append(response);
        source.Append(">(request, cancellationToken, _registry.GetSteps<").Append(req).Append(", ").Append(response);
        source.Append(">(), Resolve, ((").Append(Name(c)).AppendLine(")_handler).ExecuteAsync);");
        source.Append("        private ").Append(stepContract).AppendLine(" Resolve(global::System.Type type)");
        source.AppendLine("        {");
        foreach (var step in steps)
        {
            var closed = ClosedName(step, c);
            source.Append("            if (type == typeof(").Append(OpenName(step)).Append(")) return (").Append(stepContract).Append(")global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService(_services, typeof(").Append(closed).AppendLine("));");
        }
        source.AppendLine("            throw new global::System.InvalidOperationException($\"Unknown pipeline step '{type}'.\");");
        source.AppendLine("        }");
        source.AppendLine("    }");
    }

    private static bool Compatible(INamedTypeSymbol step, INamedTypeSymbol useCase, INamedTypeSymbol resultStep)
    {
        return step.AllInterfaces.Any(i => Same(i.OriginalDefinition, resultStep) &&
            (step.Arity == 0 ? i.TypeArguments.Zip(useCase.TypeArguments, Same).All(b => b) && i.TypeArguments.Length == useCase.TypeArguments.Length
            : GenericStepShape(step, i, resultStep) && ConstraintsSatisfied(step, useCase)));
    }

    private static bool ConstraintsSatisfied(INamedTypeSymbol step, INamedTypeSymbol useCase)
    {
        for (var index = 0; index < step.Arity; index++)
        {
            var actual = useCase.TypeArguments[index];
            foreach (var constraint in step.TypeParameters[index].ConstraintTypes)
                if (!Same(actual, constraint) && !(actual is INamedTypeSymbol named && named.AllInterfaces.Any(i => Same(i, constraint))))
                    return false;
        }
        return true;
    }

    private static bool GenericStepShape(INamedTypeSymbol step, INamedTypeSymbol contract, INamedTypeSymbol resultStep)
        => Same(contract.OriginalDefinition, resultStep) &&
           step.Arity == contract.TypeArguments.Length &&
           step.TypeParameters.Zip(contract.TypeArguments, Same).All(b => b);

    private static IEnumerable<INamedTypeSymbol> AllTypes(INamespaceSymbol ns)
    {
        foreach (var type in ns.GetTypeMembers())
        {
            yield return type;
            foreach (var nested in Nested(type)) yield return nested;
        }
        foreach (var child in ns.GetNamespaceMembers())
            foreach (var type in AllTypes(child)) yield return type;
    }

    private static IEnumerable<INamedTypeSymbol> Nested(INamedTypeSymbol type)
    {
        foreach (var child in type.GetTypeMembers())
        {
            yield return child;
            foreach (var nested in Nested(child)) yield return nested;
        }
    }

    private static bool Same(ISymbol? a, ISymbol? b) => SymbolEqualityComparer.Default.Equals(a, b);
    private static string Name(ISymbol symbol) => symbol.ToDisplayString(Format);
    private static string OpenName(INamedTypeSymbol symbol) => symbol.Arity == 0 ? Name(symbol) : Name(symbol.ConstructUnboundGenericType());
    private static string ClosedName(INamedTypeSymbol step, INamedTypeSymbol contract) => step.Arity == 0 ? Name(step) : Name(step.Construct(contract.TypeArguments.ToArray()));
    private static void Report(GeneratorExecutionContext context, DiagnosticDescriptor rule, INamedTypeSymbol type, params object[] args)
        => context.ReportDiagnostic(Diagnostic.Create(rule, type.Locations.FirstOrDefault(), args));
}
